import 'dart:convert';
import 'dart:typed_data';

/// Lightweight pure-Dart PDF 1.4 generator for exporting AI Assistant responses
/// cleanly on Android and Desktop without native print-driver dependencies.
class AiPdfExporter {
  AiPdfExporter._();

  static const double _pageWidth = 595.0; // A4 width in pt
  static const double _pageHeight = 842.0; // A4 height in pt
  static const double _marginX = 48.0;
  static const double _topY = 792.0;
  static const double _bottomY = 54.0;

  static Uint8List buildPdfBytes({
    required String title,
    required String model,
    required String markdownText,
  }) {
    final blocks = _parseBlocks(markdownText);
    final pages = <List<_PdfDrawLine>>[];
    var current = <_PdfDrawLine>[];
    var y = _topY;

    // Document title & metadata header on page 1
    current.add(_PdfDrawLine(title, 18, bold: true, y: y));
    y -= 20;
    current.add(_PdfDrawLine(
      _sanitizeAscii('Generated by Makaw AI ($model)  •  ${DateTime.now().toIso8601String().split("T").first}'),
      9.5,
      muted: true,
      y: y,
    ));
    y -= 18;
    current.add(_PdfDrawLine('_' * 82, 9.5, muted: true, y: y));
    y -= 18;

    void newPage() {
      pages.add(current);
      current = <_PdfDrawLine>[];
      y = _topY;
    }

    for (final block in blocks) {
      final lineHeight = block.fontSize * 1.42;
      final wrapped = _wrap(block.text, block.maxChars);
      for (final line in wrapped) {
        if (y - lineHeight < _bottomY) {
          newPage();
        }
        current.add(_PdfDrawLine(
          line,
          block.fontSize,
          bold: block.bold,
          mono: block.mono,
          muted: block.muted,
          indent: block.indent,
          y: y,
        ));
        y -= lineHeight;
      }
      y -= block.spaceAfter;
      if (y < _bottomY) {
        newPage();
      }
    }

    if (current.isNotEmpty || pages.isEmpty) {
      pages.add(current);
    }

    return _compilePdf(pages);
  }

  static List<_PdfBlock> _parseBlocks(String md) {
    final out = <_PdfBlock>[];
    final lines = md.replaceAll('\r\n', '\n').split('\n');
    bool inCode = false;

    for (final raw in lines) {
      final line = raw.trimRight();
      if (line.trim().startsWith('```')) {
        inCode = !inCode;
        continue;
      }
      if (inCode) {
        out.add(_PdfBlock(
          text: _sanitizeAscii(line),
          fontSize: 9.5,
          mono: true,
          indent: 10,
          maxChars: 84,
          spaceAfter: 2,
        ));
        continue;
      }

      final trimmed = line.trim();
      if (trimmed.isEmpty) {
        out.add(const _PdfBlock(text: '', fontSize: 10, maxChars: 90, spaceAfter: 6));
        continue;
      }
      if (RegExp(r'^(\-{3,}|\*{3,}|_{3,})$').hasMatch(trimmed)) {
        out.add(_PdfBlock(text: '_' * 82, fontSize: 9.5, muted: true, maxChars: 90, spaceAfter: 8));
        continue;
      }
      final hMatch = RegExp(r'^(#{1,4})\s+(.+)$').firstMatch(trimmed);
      if (hMatch != null) {
        final lvl = hMatch.group(1)!.length;
        final size = lvl == 1 ? 15.0 : lvl == 2 ? 13.5 : 12.0;
        out.add(_PdfBlock(
          text: _cleanInlineMarkdown(hMatch.group(2)!),
          fontSize: size,
          bold: true,
          maxChars: (500 / (size * 0.56)).floor(),
          spaceAfter: 5,
        ));
        continue;
      }
      if (trimmed.startsWith('>')) {
        out.add(_PdfBlock(
          text: '| ${_cleanInlineMarkdown(trimmed.replaceFirst(RegExp(r'^>\s?'), ''))}',
          fontSize: 10.5,
          muted: true,
          indent: 12,
          maxChars: 80,
          spaceAfter: 4,
        ));
        continue;
      }
      final bMatch = RegExp(r'^([\*\-\+])\s+(.+)$').firstMatch(trimmed);
      if (bMatch != null) {
        out.add(_PdfBlock(
          text: '• ${_cleanInlineMarkdown(bMatch.group(2)!)}',
          fontSize: 11,
          indent: 12,
          maxChars: 80,
          spaceAfter: 3,
        ));
        continue;
      }
      out.add(_PdfBlock(
        text: _cleanInlineMarkdown(trimmed),
        fontSize: 11,
        maxChars: 84,
        spaceAfter: 3,
      ));
    }
    return out;
  }

  static String _cleanInlineMarkdown(String s) {
    var r = s;
    r = r.replaceAllMapped(RegExp(r'\*\*(.+?)\*\*'), (m) => m.group(1)!);
    r = r.replaceAllMapped(RegExp(r'__(.+?)__'), (m) => m.group(1)!);
    r = r.replaceAllMapped(RegExp(r'`([^`]+)`'), (m) => m.group(1)!);
    r = r.replaceAllMapped(RegExp(r'\[([^\]]+)\]\(([^\)]+)\)'), (m) => '${m.group(1)} (${m.group(2)})');
    return _sanitizeAscii(r);
  }

  static String _sanitizeAscii(String s) {
    // Map common Unicode punctuation into Windows-1252 / PDFDocEncoding safe ASCII
    final replaced = s
        .replaceAll('—', '--')
        .replaceAll('–', '-')
        .replaceAll('•', '*')
        .replaceAll('’', "'")
        .replaceAll('‘', "'")
        .replaceAll('“', '"')
        .replaceAll('”', '"')
        .replaceAll('→', '->')
        .replaceAll('←', '<-')
        .replaceAll('…', '...');
    final buf = StringBuffer();
    for (final rune in replaced.runes) {
      if (rune >= 32 && rune <= 126) {
        buf.writeCharCode(rune);
      } else {
        buf.write(' ');
      }
    }
    return buf.toString();
  }

  static List<String> _wrap(String text, int maxChars) {
    if (text.isEmpty) return [''];
    if (text.length <= maxChars) return [text];
    final out = <String>[];
    var remaining = text;
    while (remaining.length > maxChars) {
      var splitAt = remaining.lastIndexOf(' ', maxChars);
      if (splitAt <= 0) splitAt = maxChars;
      out.add(remaining.substring(0, splitAt).trimRight());
      remaining = remaining.substring(splitAt).trimLeft();
    }
    if (remaining.isNotEmpty) out.add(remaining);
    return out;
  }

  static Uint8List _compilePdf(List<List<_PdfDrawLine>> pages) {
    // Object IDs:
    // 1 = Catalog
    // 2 = Pages
    // 3 = Helvetica
    // 4 = Helvetica-Bold
    // 5 = Courier
    // 6+ = each page (Page dict, then Content stream)
    final objects = <int, String>{};
    final pageIds = <int>[];

    objects[3] = '<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>';
    objects[4] = '<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica-Bold >>';
    objects[5] = '<< /Type /Font /Subtype /Type1 /BaseFont /Courier >>';

    var nextId = 6;
    for (int pIdx = 0; pIdx < pages.length; pIdx++) {
      final pageObjId = nextId++;
      final streamObjId = nextId++;
      pageIds.add(pageObjId);

      final sb = StringBuffer();
      for (final line in pages[pIdx]) {
        final fontKey = line.mono ? '/F3' : (line.bold ? '/F2' : '/F1');
        final x = (_marginX + line.indent).toStringAsFixed(1);
        final y = line.y.toStringAsFixed(1);
        final escaped = _escapePdfString(line.text);
        if (line.muted) {
          sb.writeln('0.45 0.5 0.58 rg');
        } else {
          sb.writeln('0.1 0.12 0.18 rg');
        }
        sb.writeln('BT $fontKey ${line.fontSize.toStringAsFixed(1)} Tf $x $y Td ($escaped) Tj ET');
      }
      // Footer page number
      sb.writeln('0.45 0.5 0.58 rg');
      sb.writeln(
        'BT /F1 9.0 Tf 275.0 28.0 Td (${_escapePdfString('Page ${pIdx + 1} of ${pages.length}')}) Tj ET',
      );

      final streamText = sb.toString();
      final streamBytes = latin1.encode(streamText).length;
      objects[streamObjId] = '<< /Length $streamBytes >>\nstream\n$streamText\nendstream';
      objects[pageObjId] =
          '<< /Type /Page /Parent 2 0 R /MediaBox [0 0 ${_pageWidth.toInt()} ${_pageHeight.toInt()}] '
          '/Resources << /Font << /F1 3 0 R /F2 4 0 R /F3 5 0 R >> >> /Contents $streamObjId 0 R >>';
    }

    objects[2] = '<< /Type /Pages /Count ${pageIds.length} /Kids [${pageIds.map((id) => '$id 0 R').join(' ')}] >>';
    objects[1] = '<< /Type /Catalog /Pages 2 0 R >>';

    final out = BytesBuilder();
    void writeStr(String s) => out.add(latin1.encode(s));

    writeStr('%PDF-1.4\n');
    final maxId = objects.keys.reduce((a, b) => a > b ? a : b);
    final offsets = List<int>.filled(maxId + 1, 0);

    for (int id = 1; id <= maxId; id++) {
      offsets[id] = out.length;
      writeStr('$id 0 obj\n${objects[id]}\nendobj\n');
    }

    final xrefPos = out.length;
    writeStr('xref\n0 ${maxId + 1}\n');
    writeStr('0000000000 65535 f \n');
    for (int id = 1; id <= maxId; id++) {
      writeStr('${offsets[id].toString().padLeft(10, '0')} 00000 n \n');
    }
    writeStr('trailer\n<< /Size ${maxId + 1} /Root 1 0 R >>\nstartxref\n$xrefPos\n%%EOF\n');
    return out.toBytes();
  }

  static String _escapePdfString(String s) => s
      .replaceAll('\\', '\\\\')
      .replaceAll('(', '\\(')
      .replaceAll(')', '\\)');
}

class _PdfBlock {
  final String text;
  final double fontSize;
  final bool bold;
  final bool mono;
  final bool muted;
  final double indent;
  final int maxChars;
  final double spaceAfter;

  const _PdfBlock({
    required this.text,
    required this.fontSize,
    this.bold = false,
    this.mono = false,
    this.muted = false,
    this.indent = 0,
    required this.maxChars,
    required this.spaceAfter,
  });
}

class _PdfDrawLine {
  final String text;
  final double fontSize;
  final bool bold;
  final bool mono;
  final bool muted;
  final double indent;
  final double y;

  const _PdfDrawLine(
    this.text,
    this.fontSize, {
    this.bold = false,
    this.mono = false,
    this.muted = false,
    this.indent = 0,
    required this.y,
  });
}
